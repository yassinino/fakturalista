<p>Pour une TPE, une facture impayée n'est pas un détail comptable : c'est du salaire, du loyer ou du stock qui n'est pas financé. La bonne nouvelle, c'est que la plupart des retards se réduisent avec une organisation simple et régulière.</p>

<h2>Ce que dit la loi sur les délais de paiement</h2>
<p>La loi n° 69-21, qui a modifié le Code de commerce, encadre les délais de paiement entre professionnels :</p>
<ul>
<li>à défaut d'accord entre les parties, le délai de paiement est de <strong>60 jours</strong> à compter de la date de facture ;</li>
<li>un délai convenu ne peut pas dépasser <strong>120 jours</strong> à compter de la date de facture ;</li>
<li>les entreprises dont le chiffre d'affaires dépasse 2 millions de dirhams doivent déclarer auprès de la DGI les factures payées hors délai, et des amendes s'appliquent en cas de retard.</li>
</ul>
<p>Ces règles concernent les relations entre professionnels. Faites préciser par votre comptable comment elles s'appliquent à votre entreprise et à vos clients.</p>

<h2>Étape 1 : prévenir plutôt que relancer</h2>
<ul>
<li><strong>Facturez tout de suite</strong> : la date de facture déclenche le délai. Chaque jour d'attente repousse l'encaissement.</li>
<li><strong>Écrivez une échéance précise</strong> (« à payer avant le 15/11/2026 ») plutôt que « à réception ».</li>
<li><strong>Annoncez les conditions dès le devis</strong> : acompte éventuel, échéance, mode de paiement (voir <a href="/blog/devis-factures-erreurs-tpe-maroc">les erreurs à éviter sur les devis</a>).</li>
<li><strong>Vérifiez la facture</strong> : un ICE manquant ou une TVA erronée donne au client une raison légitime de ne pas payer.</li>
</ul>

<h2>Étape 2 : suivre les échéances chaque semaine</h2>
<p>Bloquez trente minutes par semaine pour passer en revue trois listes : les factures qui arrivent à échéance dans les sept prochains jours, celles qui sont en retard, et celles qui sont payées mais pas encore enregistrées. Un tableur peut suffire au début ; un logiciel de facturation le fait automatiquement et vous évite d'oublier une facture.</p>

