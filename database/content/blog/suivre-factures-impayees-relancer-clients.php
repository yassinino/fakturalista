<h2>Modèles de messages</h2>
<h3>Rappel avant échéance</h3>
<blockquote>Bonjour Madame/Monsieur, je me permets de vous rappeler que la facture n° [numéro] d'un montant de [montant] DH arrive à échéance le [date]. Vous la trouverez en pièce jointe. Merci par avance, et n'hésitez pas à revenir vers moi pour toute question.</blockquote>
<h3>Première relance</h3>
<blockquote>Bonjour, sauf erreur de notre part, la facture n° [numéro] du [date] d'un montant de [montant] DH, échue le [date], n'a pas encore été réglée. Pourriez-vous nous indiquer la date de paiement prévue ? Si le règlement a déjà été effectué, merci de ne pas tenir compte de ce message.</blockquote>
<h3>Relance ferme</h3>
<blockquote>Bonjour, malgré nos précédents messages, la facture n° [numéro] reste impayée à ce jour, avec un retard de [nombre] jours. Nous vous remercions de procéder au règlement sous huit jours. À défaut, nous serons contraints d'engager les démarches prévues.</blockquote>

<h2>Étape 4 : enregistrer les paiements sans attendre</h2>
<p>Un paiement reçu mais non enregistré conduit à relancer un client qui a déjà payé : c'est l'erreur qui abîme le plus une relation commerciale. Rapprochez vos relevés bancaires de vos factures au moins une fois par semaine.</p>

