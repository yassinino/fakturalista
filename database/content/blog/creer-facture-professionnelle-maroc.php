<h2>Étape 6 : les conditions de paiement</h2>
<p>Indiquez la date d'échéance, les modes de paiement acceptés (virement, chèque, espèces dans les limites légales) et vos coordonnées bancaires. Entre professionnels, la loi n° 69-21 fixe le délai de paiement à 60 jours à compter de la date de facture à défaut d'accord, et plafonne un délai convenu à 120 jours. Une échéance claire facilite ensuite <a href="/blog/suivre-factures-impayees-relancer-clients">le suivi des impayés</a>.</p>

<h2>Étape 7 : envoyer et conserver</h2>
<p>Envoyez la facture en PDF et gardez une trace de l'envoi. Le CGI impose de conserver les documents comptables, dont les factures, pendant dix ans. Un outil en ligne vous évite de dépendre d'un seul ordinateur.</p>

<h2>Les erreurs les plus fréquentes</h2>
<ul>
<li>oublier l'ICE du client professionnel ;</li>
<li>réutiliser un numéro ou en sauter un en dupliquant un fichier Word ;</li>
<li>appliquer un mauvais taux de TVA après une modification ;</li>
<li>modifier une facture déjà envoyée au lieu d'émettre un document rectificatif ;</li>
<li>ne pas indiquer d'échéance, ce qui complique les relances.</li>
</ul>
<p>Nous détaillons ces pièges dans <a href="/blog/devis-factures-erreurs-tpe-maroc">devis et factures : les erreurs à éviter</a>.</p>

