<p>Une facture n'est pas qu'une demande de paiement : c'est une pièce comptable et fiscale, pour vous comme pour votre client. Au Maroc, ses mentions sont encadrées par l'article 145 du Code général des impôts (CGI). Voici comment construire une facture complète, étape par étape.</p>
<blockquote>Ce guide est informatif. Votre situation (forme juridique, régime fiscal, activité exonérée) peut ajouter des règles particulières : faites valider vos modèles par votre comptable.</blockquote>

<h2>Étape 1 : vos informations d'entreprise</h2>
<p>La facture doit identifier clairement le vendeur. Prévoyez :</p>
<ul>
<li>la raison sociale ou le nom commercial, et l'adresse ;</li>
<li>l'identifiant fiscal (IF) ;</li>
<li>l'identifiant commun de l'entreprise (ICE), obligatoire sur les factures depuis sa généralisation ;</li>
<li>le numéro de taxe professionnelle ;</li>
<li>le numéro de registre du commerce (RC) lorsque votre forme juridique y est soumise.</li>
</ul>
<p>Ces informations sont les mêmes sur toutes vos factures : saisissez-les une fois dans votre outil de facturation plutôt que de les recopier.</p>

<h2>Étape 2 : les informations du client</h2>
<p>Indiquez le nom ou la raison sociale du client et son adresse. Lorsque votre client est une entreprise, son ICE doit également figurer sur la facture : c'est ce qui lui permet de justifier la charge et, le cas échéant, de récupérer la TVA. Pour un particulier, l'ICE n'est pas demandé.</p>

<h2>Étape 3 : numéro et date</h2>
<p>Chaque facture porte un numéro unique, attribué selon une séquence continue et chronologique. Un « trou » dans la numérotation peut attirer l'attention de l'administration. Ajoutez la date d'émission et, idéalement, la date d'échéance.</p>
<p>Une facture émise ne se modifie pas et ne se supprime pas : en cas d'erreur, on émet un document rectificatif qui fait référence à la facture d'origine.</p>

<h2>Étape 4 : le détail des biens ou services</h2>
<p>Pour chaque ligne : une désignation précise, la quantité, le prix unitaire hors taxe et le montant hors taxe. Les remises accordées apparaissent clairement, ligne par ligne ou sur le total.</p>

<h2>Étape 5 : la TVA et les totaux</h2>
<p>Depuis la réforme engagée par la loi de finances 2024, la TVA marocaine converge vers deux taux : 20 % (taux normal) et 10 % (taux réduit). Si plusieurs taux s'appliquent sur la même facture, détaillez la base et le montant de TVA pour chaque taux, puis le total hors taxe, le total de TVA et le total TTC.</p>
<p>Si votre activité n'est pas soumise à la TVA (par exemple, un auto-entrepreneur dont le chiffre d'affaires reste sous les seuils, ou une opération exonérée), la facture ne doit pas en facturer. Votre comptable vous indiquera la mention à faire figurer.</p>

