<p>Lorsque votre client peut accepter le devis en ligne, la décision est enregistrée avec sa date, sans échange de documents signés et scannés.</p>

<h2>4. Transformer le devis en facture</h2>
<p>Le devis accepté doit devenir une facture sans ressaisie : mêmes lignes, mêmes prix, même TVA. Le numéro de facture est attribué au moment de l'émission, selon une séquence continue. Une fois émise, la facture ne se modifie plus ; une erreur se corrige par un document rectificatif.</p>

<h2>5. Envoyer et partager</h2>
<p>Envoyez la facture en PDF par e-mail, ou donnez à votre client un accès à un espace en ligne où il retrouve toutes ses factures et ses devis. Cette seconde option évite les demandes de renvoi de documents et les « je n'ai rien reçu ».</p>

<h2>6. Suivre l'échéance et l'encaissement</h2>
<p>Chaque facture doit porter une date d'échéance. Surveillez chaque semaine les factures qui arrivent à échéance et celles qui sont en retard, relancez selon un calendrier défini (voir <a href="/blog/suivre-factures-impayees-relancer-clients">notre méthode de relance</a>), puis enregistrez chaque paiement reçu.</p>

<h2>Les indicateurs à surveiller chaque mois</h2>
<ul>
<li><strong>Le montant des factures en retard</strong> : c'est votre trésorerie bloquée.</li>
<li><strong>Le délai moyen de paiement</strong> de vos clients, comparé à vos conditions.</li>
<li><strong>Le taux d'acceptation de vos devis</strong> : un taux en baisse signale souvent un problème de prix ou de délai de réponse.</li>
<li><strong>Le chiffre d'affaires encaissé</strong> par rapport au chiffre d'affaires facturé.</li>
</ul>

