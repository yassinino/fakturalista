<h2>1. Préparer une base propre</h2>
<p>Avant le premier document, renseignez trois éléments : les informations de votre entreprise (avec vos identifiants comme l'ICE), vos clients actifs et votre catalogue de produits ou services avec leurs prix hors taxe et leur taux de TVA. Ce travail d'une heure vous en fera gagner des dizaines.</p>

<h2>2. Créer le devis</h2>
<p>Un bon devis comporte une description précise de chaque poste, les quantités, les prix unitaires hors taxe, les remises, la TVA, le total TTC, une date de validité et vos conditions de paiement. Pour les pièges à éviter, lisez <a href="/blog/devis-factures-erreurs-tpe-maroc">devis et factures : les erreurs à éviter</a>.</p>

