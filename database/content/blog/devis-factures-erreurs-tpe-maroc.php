<p>La plupart des retards de paiement et des litiges commencent par un document imprécis. Pour une TPE, chaque erreur se paie deux fois : en temps passé à corriger, et en trésorerie qui n'arrive pas. Voici dix erreurs à repérer dans vos devis et vos factures.</p>

<h2>Les erreurs sur les devis</h2>

<h3>1. Une description trop vague</h3>
<p>« Travaux divers » ou « prestation de service » ne permettent ni au client de comparer, ni à vous de justifier un supplément plus tard. Détaillez chaque poste : ce qui est inclus, les quantités, l'unité (heure, jour, m², forfait) et le prix unitaire hors taxe.</p>

<h3>2. Aucune durée de validité</h3>
<p>Sans date de validité, un client peut vous demander d'honorer un prix des mois plus tard, alors que vos coûts ont changé. Indiquez une date d'expiration, par exemple 30 jours.</p>

<h3>3. Des conditions de paiement absentes</h3>
<p>Le devis est le bon moment pour fixer les règles : acompte éventuel, échéance de la facture, mode de paiement. Entre professionnels, rappelez-vous que la loi n° 69-21 fixe un délai de 60 jours à défaut d'accord, et qu'un délai convenu ne peut pas dépasser 120 jours à compter de la date de facture.</p>

<h3>4. Recopier le devis à la main dans la facture</h3>
<p>C'est l'erreur la plus banale et la plus coûteuse : un prix modifié, une ligne oubliée, une remise appliquée deux fois. Un outil qui <a href="/ma/logiciel-devis-facture">transforme le devis accepté en facture</a> supprime ce risque.</p>

<h2>Les erreurs sur les factures</h2>

<h3>5. Oublier l'ICE du client professionnel</h3>
<p>Lorsque votre client est une entreprise, son identifiant commun de l'entreprise (ICE) doit figurer sur la facture. Sans lui, votre client peut refuser la facture ou vous demander de la refaire, ce qui retarde le paiement.</p>

<h3>6. Des identifiants incomplets côté vendeur</h3>
<p>Votre ICE, votre identifiant fiscal, votre numéro de taxe professionnelle et, selon votre forme juridique, votre RC font partie des mentions prévues par l'article 145 du CGI. Vérifiez votre modèle une fois pour toutes avec votre comptable.</p>

<h3>7. Un mauvais taux de TVA</h3>
<p>La réforme engagée par la loi de finances 2024 a fait converger la TVA vers deux taux, 20 % et 10 %. Un ancien modèle Excel peut encore contenir 7 % ou 14 %. Contrôlez aussi les opérations exonérées et, si vous êtes auto-entrepreneur hors champ de la TVA, ne facturez pas de TVA.</p>

<h3>8. Une numérotation cassée</h3>
<p>Dupliquer un fichier Word pour créer la facture suivante est la meilleure façon d'obtenir deux factures portant le même numéro, ou un numéro sauté. La numérotation doit être continue et chronologique.</p>

<h3>9. Modifier une facture déjà envoyée</h3>
<p>Une facture émise ne se modifie pas. Si elle contient une erreur, émettez un document rectificatif qui fait référence à la facture d'origine. Modifier le PDF « en douce » crée deux versions différentes du même document, une chez vous et une chez votre client.</p>

<h3>10. Facturer trop tard, et ne pas suivre l'échéance</h3>
<p>Chaque jour de retard dans l'émission de la facture repousse d'autant l'encaissement. Facturez dès la fin de la prestation, avec une échéance explicite, puis suivez-la. Notre guide sur <a href="/blog/suivre-factures-impayees-relancer-clients">la relance des factures impayées</a> propose un calendrier de relance simple.</p>

